// Разбор кадровой выгрузки. Тесты не требуют базы — проверяется чистая логика.
const test = require("node:test")
const assert = require("node:assert/strict")

const { detectColumns, isFio, titleCase } = require("../server/residents-import")

test("колонки определяются по заголовку в обычной выгрузке", () => {
	const cols = detectColumns(
		["ФИО", "Таб. номер", "Организация", "Должность", "Телефон"],
		[["Смирнов Олег Иванович", "A-1001", "ППГХО", "Слесарь", "+7 900 111-22-33"]],
	)
	assert.equal(cols.name, 0)
	assert.equal(cols.tab, 1, "табельный с буквой тоже должен распознаваться")
	assert.equal(cols.company, 2)
	assert.equal(cols.position, 3)
	assert.equal(cols.phone, 4)
})

test("заголовок, разошедшийся с содержимым, не сбивает разбор", () => {
	// Выгрузка заказчика: под «Табельный номер» лежат ФИО, а сам табельный — под «Таб.№».
	// Оба заголовка подходят под слово «таб», поэтому решать должно содержимое.
	const cols = detectColumns(
		["Таб.№", "Табельный номер", "Шт.должность (полное)", "Подразделение (полное)", "Балансовая единица"],
		[
			["15600025", "ИВАНОВ ИВАН ИВАНОВИЧ", "Главный специалист", "Геолого-геофизическая группа", "АО «Хиагда»"],
			["15600429", "Петров Петр Петрович", "Главный специалист", "Группа планирования", "АО «Хиагда»"],
		],
	)
	assert.equal(cols.name, 1, "ФИО лежат во второй колонке вопреки её заголовку")
	assert.equal(cols.tab, 0)
	assert.equal(cols.department, 3)
	assert.equal(cols.company, 4)
	assert.equal(cols.position, 2)
})

test("колонки находятся и без заголовков", () => {
	const cols = detectColumns(
		["", "", "", ""],
		[
			["15600025", "Иванов Иван Иванович", "Проходчик", "Цех №1"],
			["15600429", "Петров Пётр Петрович", "Слесарь", "Цех №1"],
		],
	)
	assert.equal(cols.name, 1)
	assert.equal(cols.tab, 0)
})

test("ФИО отличается от служебных строк", () => {
	assert.ok(isFio("Иванов Иван Иванович"))
	assert.ok(isFio("Петров-Водкин Кузьма Сергеевич"))
	assert.ok(isFio("Иванов Иван"))
	assert.ok(!isFio("Всего: 53"), "итоговая строка не должна попасть в список")
	assert.ok(!isFio("Иванов И.И."), "инициалы с точками не разбираются на части")
	assert.ok(!isFio(""))
	assert.ok(!isFio("Ivanov Ivan"))
})

test("регистр ФИО приводится к единому виду", () => {
	assert.equal(titleCase("ИВАНОВ ИВАН ИВАНОВИЧ"), "Иванов Иван Иванович")
	assert.equal(titleCase("петров пётр петрович"), "Петров Пётр Петрович")
	assert.equal(titleCase("ПЕТРОВ-ВОДКИН КУЗЬМА"), "Петров-Водкин Кузьма")
	assert.equal(titleCase("  Иванов   Иван  "), "Иванов Иван", "лишние пробелы схлопываются")
})
